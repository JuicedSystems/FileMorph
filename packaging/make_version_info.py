"""Write packaging/version_info.txt (the Windows file-properties version) from filemorph.__version__."""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from filemorph import __version__  # noqa: E402

nums = [int(x) for x in re.findall(r"\d+", __version__)[:3]]
nums += [0] * (4 - len(nums))
tup = ", ".join(map(str, nums))
text = f"""# Generated by packaging/make_version_info.py from filemorph/__init__.py - don't edit by hand.
VSVersionInfo(
  ffi=FixedFileInfo(filevers=({tup}), prodvers=({tup}), mask=0x3f, flags=0x0, OS=0x40004,
                    fileType=0x1, subtype=0x0, date=(0, 0)),
  kids=[
    StringFileInfo([StringTable('040904B0', [
      StringStruct('CompanyName', 'FileMorph'),
      StringStruct('FileDescription', 'FileMorph - drag-and-drop file converter'),
      StringStruct('FileVersion', '{__version__}'),
      StringStruct('InternalName', 'FileMorph'),
      StringStruct('LegalCopyright', 'Copyright (c) 2026 Juiced Systems. AGPL-3.0'),
      StringStruct('OriginalFilename', 'FileMorph.exe'),
      StringStruct('ProductName', 'FileMorph'),
      StringStruct('ProductVersion', '{__version__}')])]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""
(ROOT / "packaging" / "version_info.txt").write_text(text, encoding="utf-8")
print(f"version_info.txt -> {__version__}")
